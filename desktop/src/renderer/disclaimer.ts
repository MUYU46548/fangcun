/** 本机是否已就**当前版本**确认过（版本抬格后自动视为未确认） */
export function hasAckedDisclaimer(): boolean {
  try {
    const raw = localStorage.getItem(DISCLAIMER_ACK_KEY)
    if (!raw) return false
    const o = JSON.parse(raw)
    return !!o && o.v === DISCLAIMER_VERSION
  } catch {
    // 存储不可用 / 坏数据 → 按**已确认**处理：绝不把用户挡在软件外面
    return true
  }
}

/** 上次确认时间（ISO 串；没确认过返回空串） */
export function ackedDisclaimerAt(): string {
  try {
    const raw = localStorage.getItem(DISCLAIMER_ACK_KEY)
    if (!raw) return ''
    const o = JSON.parse(raw)
    return (o && typeof o.at === 'string') ? o.at : ''
  } catch {
    return ''
  }
}

/** 记下本次确认（返回写入的时间串） */
export function ackDisclaimer(): string {
  const at = new Date().toISOString()
  try {
    localStorage.setItem(DISCLAIMER_ACK_KEY, JSON.stringify({ v: DISCLAIMER_VERSION, at }))
  } catch { /* 存储不可用就只在本次会话里认了，不阻塞使用 */ }
  return at
}
