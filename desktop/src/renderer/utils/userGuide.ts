/**
 * 搜索：标题 / 关键词 / 正文三处一起匹配，全大小写不敏感。
 * 空查询返回全部（目录保持完整，不因空搜索而变空）。
 */
export function searchGuide(q: string): GuideSection[] {
  const s = String(q || '').trim().toLowerCase()
  if (!s) return GUIDE_SECTIONS
  return GUIDE_SECTIONS.filter((sec) => {
    if (sec.title.toLowerCase().includes(s)) return true
    if (sec.keywords.some((k) => k.toLowerCase().includes(s))) return true
    return sec.blocks.some((b) => {
      if (b.t === 'p' || b.t === 'warn' || b.t === 'tip') return b.v.toLowerCase().includes(s)
      if (b.t === 'steps' || b.t === 'list') return b.v.some((x) => x.toLowerCase().includes(s))
      return b.v.some((pair) => (pair[0] + ' ' + pair[1]).toLowerCase().includes(s))
    })
  })
}
