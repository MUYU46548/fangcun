/**
 * 方寸内置手册的**唯一真源**（2026-11-16 · 与另两款自有产品统一版式）
 *
 * ## 为什么抽这个文件
 *
 * 用户 2026-11-16：「**三款自有产品的内置用户手册全都不一样，神了，
 * 全是看都没看从头瞎造，而且每个都不好用，很丑。分类和检索也是必做，方寸手册没有。**」
 *
 * 三处实情（核实过）：
 *   · **产品 A** —— 弹窗式、左目录、搜索、`keywords` 可搜、每条带 `cite` 出处。**最好用，抄它。**
 *   · **产品 B** —— markdown 文件按前缀排序后渲染。
 *   · **方寸** —— 整页平铺 10 节，**无目录、无搜索**，全贴左边。
 *
 * 抄的是**结构**，不是样式：
 *   ① **文案只在本文档**（单一事实源）—— 组件零文案，改字不动 .vue；
 *   ② 每节带 `keywords`（搜索命中面）+ `cite`（仓库内出处，防止手册长成传闻）；
 *   ③ 内容必须是**可照做**的步骤，指不出的路不写进来。
 *
 * ## 与产品 A 的两处有意不同（不改就是抄错）
 *
 * 1. 那边用 `.js`；方寸用 **`.ts`** —— 因为 `check-ui-copy.cjs` 的 `walk()` 只扫
 *    `.ts|.vue`，写成 `.js` 会**绕过界面文案守卫**且拿不到类型检查。
 * 2. 那边的 `cite` 直接给用户看；方寸**也给人看但措辞改成「维护者注」** ——
 *    用户原话是"使用手册本身也难用得要死"，出处行不该占正文注意力。
 *
 * ## ⚠ 私有专名
 *
 * 本文件是**会打进安装包**的，所以**任何自有产品的专名都不许出现**。
 * 词表在 `scripts/privacy-terms.cjs`（base64，明文不落库），守卫 `scripts/privacy-scan.cjs`。
 */

/** 章节。`blocks[].t` 取值： */
export type GuideBlock =
  /** 段落 */
  | { t: 'p'; v: string }
  /** 有序步骤（要能照着做） */
  | { t: 'steps'; v: string[] }
  /** 无序要点 */
  | { t: 'list'; v: string[] }
  /** 快捷键表 [[键, 说明], …] */
  | { t: 'key'; v: [string, string][] }
  /** 容易踩的坑 */
  | { t: 'warn'; v: string }
  /** 省时间的做法 */
  | { t: 'tip'; v: string }

export interface GuideSection {
  id: string
  title: string
  /** 搜索命中面：用户会敲的词都放这儿（正文里没写也要能搜到） */
  keywords: string[]
  blocks: GuideBlock[]
  /** 维护者注：这节的事实出自哪个文件（不写 = 下一个人不敢改） */
  cite?: string
}

